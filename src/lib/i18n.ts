export type Copy = typeof en;

export function useI18n() {
  const language = useNovaUi((state) => state.language);
  return { language, t: (language === "ar" ? ar : en) as Copy, isAr: language === "ar" };
}

export function serviceText(
  language: Lang,
  item: { name: string; nameAr?: string; description?: string; descriptionAr?: string },
) {
  const useAr = language === "ar";
  return {
    name: useAr && item.nameAr ? item.nameAr : item.name,
    description: useAr && item.descriptionAr ? item.descriptionAr : (item.description ?? ""),
  };
}

export function categoryName(t: Copy, slug: string): string {
  if (slug === "games") return t.games;
  if (slug === "apps") return t.apps;
  if (slug === "subscriptions") return t.subscriptions;
  if (slug === "mobile") return t.mobile;
  return slug;
}

export function targetText(t: Copy, category: string): string {
  if (category === "mobile") return t.targetPhone;
  if (category === "subscriptions") return t.targetAccount;
  if (category === "apps") return t.targetAccountId;
  return t.targetPlayer;
}

export function requestStatusText(t: Copy, status: string): string {
  if (status === "APPROVED" || status === "approved") return t.statusApproved;
  if (status === "REJECTED" || status === "rejected") return t.statusRejected;
  return t.statusProcessing;
}

export function orderStatusText(t: Copy, status: string): string {
  if (status === "delivered") return t.delivered;
  if (status === "processing" || status === "PROCESSING") return t.orderProcessing;
  return status;
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

